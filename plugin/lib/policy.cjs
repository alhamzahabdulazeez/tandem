'use strict';
/**
 * Deterministic decisions about file writes and shell commands.
 * Pure functions: inputs in, a verdict out. No model, no I/O beyond what the
 * caller passes in.
 *
 * Verdict shape: { decision: 'deny' | 'allow' | 'none', reason, rule }
 *   deny  -> the action is refused and the reason is sent to the agent
 *   allow -> the action is pre-approved (no permission prompt)
 *   none  -> no opinion; Claude Code's normal permission flow applies
 */

const SECRETS = require('./secrets.cjs');
const ENV_FILE_RE = /(?:^|\/)\.env(?:\.(?!example$|sample$|template$|dist$)[^/]*)?$/i;

const TEST_FILE_RE = /(?:^|\/)(?:test|tests|__tests__|spec|specs)\/|\.(?:test|spec)\.(?:[cm]?[jt]sx?)$|(?:^|\/)test_[^/]*\.py$|_test\.(?:py|go)$|(?:^|\/)[^/]*_spec\.rb$|(?:^|\/)[^/]*Tests?\.(?:java|kt|cs)$/i;
const SNAPSHOT_RE = /\.(?:snap|snapshot)$|(?:^|\/)__snapshots__\//i;

const ALWAYS_DENY = [
  { re: /(?:^|\/)\.git\//, rule: 'git-internals', why: 'files inside .git are repository internals' },
];

const PROTECTED = [
  { re: ENV_FILE_RE, rule: 'secrets', why: 'environment files hold secrets' },
  { re: /(?:^|\/)(?:id_rsa|id_ed25519|id_ecdsa)(?:\.pub)?$|\.pem$|\.p12$|\.key$/i, rule: 'secrets', why: 'key material' },
  { re: /(?:^|\/)(?:package-lock\.json|npm-shrinkwrap\.json|yarn\.lock|pnpm-lock\.yaml|bun\.lockb|poetry\.lock|Pipfile\.lock|Cargo\.lock|go\.sum|composer\.lock|Gemfile\.lock)$/, rule: 'lockfile', why: 'lockfiles are generated by the package manager' },
  { re: /(?:^|\/)\.github\/workflows\/|(?:^|\/)\.gitlab-ci\.ya?ml$|(?:^|\/)\.circleci\//, rule: 'ci-config', why: 'CI configuration controls what gets verified' },
  { re: /(?:^|\/)\.claude\/(?:settings(?:\.local)?\.json|tandem\.json)$/, rule: 'supervisor-config', why: 'this file controls the supervisor itself' },
];

const ASSERTION_RE = /\b(?:assert(?:\.\w+)?|expect|should|t\.(?:ok|equal|equals|is|same|deepEqual|strictEqual|throws|notOk|true|false|Error|Errorf|Fatal|Fatalf)|self\.assert\w*|require\.\w+)\s*\(|\.(?:toBe|toEqual|toStrictEqual|toThrow|toMatch|toHaveBeenCalled\w*|toContain|toHaveLength|toBeTruthy|toBeFalsy|toBeNull|toBeDefined|rejects|resolves)\b|^\s*assert\s/gm;
const SKIP_RE = /\b(?:it|test|describe|context|suite)\.(?:skip|todo)\b|\b(?:xit|xdescribe|xtest|xcontext)\s*\(|@pytest\.mark\.skip|@unittest\.skip|\bt\.Skip\(|@Disabled\b|@Ignore\b/g;
const ONLY_RE = /\b(?:it|test|describe|context|suite)\.only\b|\b(?:fit|fdescribe)\s*\(/g;

function count(re, text) {
  const m = String(text || '').match(re);
  return m ? m.length : 0;
}

function isTestFile(rel) { return TEST_FILE_RE.test(rel) || SNAPSHOT_RE.test(rel); }

/** Apply an Edit/MultiEdit/Write tool input to the current file content. */
function applyEdit(toolName, input, before) {
  const cur = before == null ? '' : String(before);
  if (toolName === 'Write') return String(input.content || '');
  const one = (text, e) => {
    const oldS = String(e.old_string || '');
    const newS = String(e.new_string || '');
    if (!oldS) return text + newS;
    return e.replace_all ? text.split(oldS).join(newS) : text.replace(oldS, () => newS);
  };
  if (toolName === 'MultiEdit' && Array.isArray(input.edits)) return input.edits.reduce(one, cur);
  if (toolName === 'Edit') return one(cur, input);
  return null;
}

/** Compare a test file before and after a write. Returns a list of findings. */
function weakening(before, after) {
  const out = [];
  if (after == null) return out;
  const a0 = count(ASSERTION_RE, before);
  const a1 = count(ASSERTION_RE, after);
  if (a1 < a0) out.push(`removes ${a0 - a1} assertion(s) (${a0} -> ${a1})`);
  if (count(SKIP_RE, after) > count(SKIP_RE, before)) out.push('adds a skipped or todo test');
  if (count(ONLY_RE, after) > count(ONLY_RE, before)) out.push('adds .only / fit, which silently disables the rest of the suite');
  return out;
}

/** True when every non-blank line of `before` survives, in order, in `after`. */
function isAppendOnly(before, after) {
  if (after == null) return false;
  const b = String(before).split(/\r?\n/).map((l) => l.trim()).filter(Boolean);
  const a = String(after).split(/\r?\n/).map((l) => l.trim()).filter(Boolean);
  let i = 0;
  for (const line of a) { if (i < b.length && line === b[i]) i++; }
  return i === b.length;
}

function list(arr) {
  return arr.length ? arr.join(', ') : '(none named)';
}

/**
 * Decide on a file write.
 * ctx: { rel, exists, preexisting, toolName, input, before, scope, cfg, scratch, priorBlocks }
 *   preexisting: the file existed before the current request (append-only protects only those)
 */
function decideWrite(ctx) {
  const { rel, scope, cfg } = ctx;
  if (rel == null) {
    if (ctx.scratch && ctx.absPath && ctx.absPath.startsWith(ctx.scratch)) return { decision: 'allow', rule: 'scratch' };
    return { decision: 'none', rule: 'outside-project' };
  }
  const named = new Set(scope.named || []);
  const isNamed = named.has(rel);
  const redirect = (scope.named && scope.named.length)
    ? ` Make the change in the files this task is about instead: ${list(scope.named)}.`
    : ' Make the change in the source files that implement the behaviour instead.';
  const repeat = ctx.priorBlocks > 0
    ? ` This is refusal #${ctx.priorBlocks + 1} for this file: do not retry it, change approach.`
    : '';

  for (const p of ALWAYS_DENY) {
    if (p.re.test(rel)) return { decision: 'deny', rule: p.rule, reason: `Tandem blocked writing ${rel}: ${p.why}.${repeat}` };
  }

  const extra = (cfg.protect || []).map((s) => { try { return new RegExp(s); } catch { return null; } }).filter(Boolean);
  for (const p of PROTECTED.concat(extra.map((re) => ({ re, rule: 'project-protected', why: 'the project config protects it' })))) {
    if (p.re.test(rel) && !isNamed) {
      return { decision: 'deny', rule: p.rule, reason: `Tandem blocked writing ${rel}: ${p.why}, and the task does not name it.${redirect}${repeat}` };
    }
  }

  if (cfg.checkSecrets !== false && !ENV_FILE_RE.test(rel)) {
    const afterS = applyEdit(ctx.toolName, ctx.input || {}, ctx.before);
    const found = afterS == null ? [] : SECRETS.added(ctx.before || '', afterS);
    if (found.length) {
      return {
        decision: 'deny',
        rule: 'secret-in-code',
        reason: `Tandem blocked writing ${rel}: it would put a credential in the source (${SECRETS.describe(found)}). Read it from the environment instead (process.env / os.environ) and keep the value in .env, which is not committed.${repeat}`,
      };
    }
  }

  if (isTestFile(rel)) {
    const testsAllowed = cfg.allowTestEdits === true || (cfg.allowTestEdits !== false && (scope.testsAllowed || isNamed));
    const policy = cfg.testPolicy || 'append-only';
    if (!testsAllowed && policy === 'readonly') {
      const verify = ctx.scratch
        ? ` To check your work, run the existing test command, or put a throwaway script in ${ctx.scratch}.`
        : ' To check your work, run the existing test command.';
      return {
        decision: 'deny',
        rule: 'test-readonly',
        reason: `Tandem blocked ${ctx.exists ? 'editing' : 'creating'} ${rel}: tests are read-only for this task because the request does not ask for test changes.${redirect}${verify}${repeat}`,
      };
    }
    const protectedTest = ctx.preexisting === undefined ? ctx.exists : ctx.preexisting;
    if (!testsAllowed && protectedTest && policy === 'append-only') {
      const afterA = applyEdit(ctx.toolName, ctx.input || {}, ctx.before);
      if (!isAppendOnly(ctx.before || '', afterA)) {
        return {
          decision: 'deny',
          rule: 'test-modified',
          reason: `Tandem blocked this edit to ${rel}: existing tests are append-only for this task. You may add new test cases, but not change or remove existing ones. If the request really conflicts with an existing test, stop and tell the user which test conflicts and why, instead of changing it.${redirect}${repeat}`,
        };
      }
    }
    const after = applyEdit(ctx.toolName, ctx.input || {}, ctx.before);
    const w = weakening(ctx.before || '', after);
    if (w.length) {
      return { decision: 'deny', rule: 'test-weakening', reason: `Tandem blocked this edit to ${rel}: it ${w.join('; ')}. Fix the code so the existing assertions pass; do not weaken the tests.${repeat}` };
    }
  }

  const after = applyEdit(ctx.toolName, ctx.input || {}, ctx.before);
  if (after != null && /passWithNoTests/.test(after) && !/passWithNoTests/.test(ctx.before || '')) {
    return { decision: 'deny', rule: 'test-weakening', reason: `Tandem blocked this edit to ${rel}: passWithNoTests makes an empty test run count as success.${repeat}` };
  }

  return { decision: cfg.autoApprove ? 'allow' : 'none', rule: 'in-scope' };
}

