const BASH_DENY = [
  { re: /\bgit\s+reset\s+(?:[^|;&]*\s)?--hard\b/, rule: 'discard-work', why: 'git reset --hard discards uncommitted work' },
  { re: /\bgit\s+clean\s+(?:[^|;&]*\s)?-[a-zA-Z]*f/, rule: 'discard-work', why: 'git clean -f deletes untracked files' },
  { re: /\bgit\s+(?:checkout|restore)\s+(?:--\s+)?\.(?:\s|$|;|&)/, rule: 'discard-work', why: 'this discards every uncommitted change' },
  { re: /\bgit\s+stash\s+(?:drop|clear)\b/, rule: 'discard-work', why: 'this destroys stashed work' },
  { re: /\bgit\s+push\b[^|;&]*(?:\s--force(?:-with-lease)?\b|\s-f\b)/, rule: 'force-push', why: 'force-push rewrites shared history' },
  { re: /\bgit\s+push\b/, rule: 'push', why: 'publishing to a remote needs the owner\'s decision' },
  { re: /\brm\s+(?:-[a-zA-Z]*\s+)*-[a-zA-Z]*[rR][a-zA-Z]*\s+(?:-[a-zA-Z]+\s+)*(?:\/|~|\$HOME|\.\.?|\*|\.git)(?:\/)?(?:\s|$|;|&)/, rule: 'mass-delete', why: 'recursive delete of a root, home, parent, wildcard or .git path' },
  { re: /\b(?:curl|wget)\b[^|;&]*\|\s*(?:sudo\s+)?(?:ba|z|da)?sh\b/, rule: 'pipe-to-shell', why: 'piping a download into a shell runs unreviewed code' },
  { re: /(?:^|[;&|]\s*)sudo\b/, rule: 'privilege', why: 'sudo needs a human' },
  { re: /\b(?:mkfs(?:\.\w+)?|dd\s+if=)|:\(\)\s*\{\s*:\|:&\s*\};:/, rule: 'destructive', why: 'destructive system command' },
  { re: /\b(?:npm|yarn|pnpm|bun)\s+publish\b|\bcargo\s+publish\b|\btwine\s+upload\b/, rule: 'publish', why: 'publishing a package is irreversible' },
  { re: /\b(?:cat|less|more|head|tail|bat|strings|base64|xxd|cp|scp)\b[^|;&]*(?:\.env(?:\.\w+)?\b|id_rsa|id_ed25519|\.pem\b|\.p12\b|\bcredentials\b)/, rule: 'secrets', why: 'this reads secret material' },
  { re: /\b(?:node|deno|bun|python3?|py|perl|ruby)\b[^|;&]*\s-(?:e|c|p|-eval|-print)\b[^|;&]*(?:['"/](?:\.env(?:\.\w+)?|id_rsa|id_ed25519|[\w-]+\.pem|credentials)['"\s])/, rule: 'secrets', why: 'this reads secret material' },
  { re: /\.claude\/(?:settings(?:\.local)?\.json|tandem\.json)/, rule: 'supervisor-config', why: 'commands may not touch the supervisor configuration' },
];

const SAFE_BASH = [
  /^(?:npm|pnpm|yarn|bun)\s+(?:test|t|run\s+(?:test|lint|build|typecheck|check|format)[\w:-]*)(?:\s|$)/,
  /^npx\s+(?:--no-install\s+)?(?:tsc|eslint|prettier|vitest|jest|mocha|biome|tandem-check)\b/,
  // Never node -e / -p / python -c: inline code can write anywhere, so it is not "safe".
  /^node\s+(?:--test\b|--check\b)/,
  /^(?:python3?|py)\s+-m\s+(?:pytest|unittest|py_compile|mypy|ruff|flake8)\b/,
  /^(?:pytest|mypy|ruff|flake8|tox)\b/,
  /^go\s+(?:test|vet|build)\b/,
  /^cargo\s+(?:test|check|build|clippy|fmt\s+--check)\b/,
  /^git\s+(?:status|diff|log|show|rev-parse|ls-files|blame|grep)\b(?![^|;&]*--output)/,
  /^git\s+branch(?:\s+(?:-a|-r|-v|-vv|--list|--show-current|--contains\s+\S+))*\s*$/,
  /^(?:ls|pwd|cat|head|tail|wc|grep|egrep|rg|find|tree|file|stat|which|echo|uniq|diff|du|cut|tr|nl|less|more|true)\b/,
  /^sort\b(?![^|;&]*\s-o)/,
  /^sed\s+-n\b/,
];

// Every segment of a pipeline/sequence must be safe; only harmless redirects.
function isSafeCommand(cmd) {
  if (/[`]|\$\(|<\(|>\(/.test(cmd)) return false;
  const cleaned = cmd.replace(/\s*\d?>&\d\b/g, ' ').replace(/\s*\d?>\s*\/dev\/null\b/g, ' ');
  if (/>/.test(cleaned)) return false;
  if (/(?:^|\s)find\b[^|;&]*\s-(?:exec|execdir|delete|ok)\b/.test(cleaned)) return false;
  const segs = cleaned.split(/\|\||&&|;|\|/).map((x) => x.trim()).filter(Boolean);
  return segs.length > 0 && segs.every((seg) => SAFE_BASH.some((re) => re.test(seg.replace(/^cd\s+\S+\s*$/, 'true'))));
}

const INLINE_CODE = /\b(?:node|deno|bun)\s+(?:[^|;&]*\s)?(?:-e|-p|--eval|--print)\b|\b(?:python3?|py)\s+(?:[^|;&]*\s)?-c\b|\b(?:perl|ruby)\s+(?:[^|;&]*\s)?-[a-zA-Z]*e\b/;
const INLINE_WRITE = /writeFile|appendFile|createWriteStream|unlink|rmSync|rmdir|renameSync|copyFile|truncate|open\s*\([^)]*['"][wa+]|\.write\(|os\.remove|shutil\.|Path\([^)]*\)\.(?:write|unlink)|File\.write|>>?\s*\$|\bprint\s*\{?\s*\$fh/;

/** Quoted path-like strings inside inline code that also writes. */
function inlineWriteTargets(cmd) {
  if (!INLINE_CODE.test(cmd) || !INLINE_WRITE.test(cmd)) return [];
  const out = [];
  for (const m of cmd.matchAll(/(['"`])([^'"`\s]{1,200})\1/g)) {
    const v = m[2].replace(/\\/g, '/');
    if (/[./]/.test(v) && !/^\w+$/.test(v)) out.push(v);
  }
  return out;
}

/** Paths a shell command would write to (only for clear write forms). */
function shellWriteTargets(cmd) {
  const targets = [];
  const strip = (t) => t.replace(/^['"]|['"]$/g, '');
  for (const m of cmd.matchAll(/(?:^|[^\d&])>{1,2}\s*([^\s;&|]+)/g)) targets.push(strip(m[1]));
  for (const seg of cmd.split(/&&|\|\||;|\|/)) {
    const toks = seg.trim().split(/\s+/).map(strip);
    const verb = toks[0];
    const args = toks.slice(1).filter((t) => t && !t.startsWith('-'));
    if (verb === 'sed' && /\s-[a-zA-Z]*i/.test(seg)) targets.push(...args.slice(1));
    else if (verb === 'perl' && /\s-[a-zA-Z]*i/.test(seg)) targets.push(...args.slice(1));
    else if (['rm', 'truncate', 'tee', 'unlink'].includes(verb)) targets.push(...args);
    else if (['mv', 'cp'].includes(verb) && args.length >= 2) targets.push(args[args.length - 1], ...(verb === 'mv' ? args.slice(0, -1) : []));
  }
  return targets;
}

/**
 * Decide on a shell command.
 * ctx: { command, scope, cfg, toRel(path) -> rel|null, exists(rel) -> bool, repeats }
 */
function decideBash(ctx) {
  const cmd = String(ctx.command || '').trim();
  if (!cmd) return { decision: 'none', rule: 'empty' };
  const named = new Set((ctx.scope && ctx.scope.named) || []);

  for (const p of BASH_DENY) {
    if (p.rule === 'push' && ctx.cfg.allowPush) continue;
    if (p.re.test(cmd)) {
      return { decision: 'deny', rule: p.rule, reason: `Tandem blocked this command: ${p.why}. Find a non-destructive way, or leave this step for the owner and say so in your summary.` };
    }
  }

  const testsAllowed = ctx.cfg.allowTestEdits === true || (ctx.cfg.allowTestEdits !== false && ctx.scope && ctx.scope.testsAllowed);
  const writes = shellWriteTargets(cmd).concat(inlineWriteTargets(cmd));
  if (ctx.cfg.checkSecrets !== false && writes.some((w) => !ENV_FILE_RE.test(w))) {
    const found = SECRETS.scan(cmd);
    if (found.length) {
      return { decision: 'deny', rule: 'secret-in-code', reason: `Tandem blocked this command: it writes a credential into a file (${SECRETS.describe(found)}). Keep it in .env and read it from the environment.` };
    }
  }
  for (const t of shellWriteTargets(cmd).concat(inlineWriteTargets(cmd))) {
    const rel = ctx.toRel ? ctx.toRel(t) : t;
    if (!rel) continue;
    // Creating a NEW test file is adding tests, which append-only allows; the
    // finish gate still checks it for .only/.skip. Existing ones stay shell-proof.
    const isNew = ctx.exists ? !ctx.exists(rel) : false;
    const newOk = isNew && (ctx.cfg.testPolicy || 'append-only') === 'append-only';
    if (isTestFile(rel) && !testsAllowed && !named.has(rel) && ctx.cfg.testPolicy !== 'free' && !newOk) {
      return { decision: 'deny', rule: 'test-readonly', reason: `Tandem blocked this command: it would modify the test file ${rel} from the shell, where the change cannot be checked. Fix the implementation; to add a test case, use the Edit tool so Tandem can confirm the change only adds.` };
    }
    for (const p of PROTECTED) {
      if (p.re.test(rel) && !named.has(rel)) {
        return { decision: 'deny', rule: p.rule, reason: `Tandem blocked this command: it would modify ${rel} (${p.why}).` };
      }
    }
  }

  if (ctx.repeats >= (ctx.cfg.repeatLimit || 3)) {
    return {
      decision: 'deny',
      rule: 'loop',
      reason: `Tandem blocked this command: you have run exactly this ${ctx.repeats} times with no file change in between, so the result will not change. Change the code or try a different approach first.`,
    };
  }

  if (ctx.cfg.autoApprove && isSafeCommand(cmd)) {
    return { decision: 'allow', rule: 'safe-command' };
  }
  return { decision: 'none', rule: 'no-opinion' };
}

